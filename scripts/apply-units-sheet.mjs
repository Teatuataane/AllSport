#!/usr/bin/env node
// Compiles the reviewed WORKOUT_UNITS_REVIEW.md into lib/unitSheet.ts.
// Idempotent: running it twice produces the same file.
//
//   node scripts/apply-units-sheet.mjs [--dry]
//
// Refuses to write anything if the sheet has a single problem, and lists them
// all at once so one review pass fixes every one.

import fs from 'node:fs'

const SHEET = 'WORKOUT_UNITS_REVIEW.md'
const OUT = 'lib/unitSheet.ts'
const RULES = ['set', 'hold', 'distance', 'attempts', 'game', 'round']

/** Parse the sheet against the roster's slugs. Exported for the drift test. */
export function compile(sheet, eventDataSrc) {
  const roster = [...eventDataSrc.matchAll(/^\s*slug: '([^']+)'/gm)].map(m => m[1])
  const rows = []
  const problems = []
  for (const line of sheet.split('\n')) {
    const m = line.match(/^\|\s*`([^`]+)`\s*\|([^|]*)\|([^|]*)\|([^|]*)\|([^|]*)\|/)
    if (!m) continue
    const [, slug, , , ruleCell, perCell] = m
    const rule = ruleCell.trim()
    const per = Number(perCell.trim())
    if (!roster.includes(slug)) problems.push(`${slug}: not an event on the roster`)
    if (!RULES.includes(rule)) problems.push(`${slug}: rule "${rule}" is not one of ${RULES.join(', ')}`)
    if (!(per > 0) || !Number.isFinite(per)) problems.push(`${slug}: per "${perCell.trim()}" must be a positive number`)
    if (rows.some(r => r.slug === slug)) problems.push(`${slug}: listed twice`)
    rows.push({ slug, rule, per })
  }
  for (const slug of roster) if (!rows.some(r => r.slug === slug)) problems.push(`${slug}: missing from the sheet`)
  if (problems.length) throw new Error(`${SHEET} has ${problems.length} problem(s):\n  ${problems.join('\n  ')}`)
  return rows.sort((a, b) => a.slug.localeCompare(b.slug))
}

export function render(rows) {
  return [
    '// GENERATED by scripts/apply-units-sheet.mjs from WORKOUT_UNITS_REVIEW.md.',
    '// Do not edit: change the sheet and re-run the script. __tests__/units.test.ts',
    '// fails if this file and the sheet ever disagree.',
    '//',
    '// What one effort unit is, per event. `per` is completions per unit, except on',
    "// a 'distance' rule, where it is metres per unit. See lib/units.ts.",
    '',
    "export type UnitRule = 'set' | 'hold' | 'distance' | 'attempts' | 'game' | 'round'",
    '',
    'export const UNIT_SHEET: Readonly<Record<string, { rule: UnitRule; per: number }>> = {',
    ...rows.map(r => `  '${r.slug}': { rule: '${r.rule}', per: ${r.per} },`),
    '}',
    '',
  ].join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  let rows
  try {
    rows = compile(fs.readFileSync(SHEET, 'utf8'), fs.readFileSync('lib/eventData.ts', 'utf8'))
  } catch (e) {
    console.error(e.message)
    process.exit(1)
  }
  const ts = render(rows)
  const counts = rows.reduce((m, r) => ({ ...m, [r.rule]: (m[r.rule] ?? 0) + 1 }), {})
  console.log(`${rows.length} events compiled: ${Object.entries(counts).map(([k, n]) => `${n} ${k}`).join(', ')}`)
  if (process.argv.includes('--dry')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
    console.log(cur === ts ? `${OUT} is up to date` : `${OUT} would change`)
  } else {
    fs.writeFileSync(OUT, ts)
    console.log(`wrote ${OUT}`)
  }
}
