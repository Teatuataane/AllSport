#!/usr/bin/env node
// ─── Build the suburb and school lists migration (multi-location step 9) ────
// Writes the INSERTs for nz_suburbs and nz_schools (20261123230958) from the
// published sources, Canterbury only (Tāne, 24 Nov 2026):
//
//   --sa2 <file>      Canterbury statistical area 2 areas, one per line:
//                     code <TAB> name <TAB> district <TAB> NZDep2023 decile
//                     Made from two University of Otago NZDep2023 files
//                     (otago.ac.nz, "Socioeconomic Deprivation Indexes"):
//                     NZDep2023_WgtAvSA2 (the SA2 decile) joined to
//                     NZDep2023_SA1_withHigherGeo (each SA2's regional
//                     council, and its district by most population). Areas
//                     with no decile (nobody lives there) are left out.
//                     The site sits behind a Cloudflare check, so the join was
//                     run in a browser on 24 Nov 2026: 323 Canterbury SA2s, 318
//                     with a decile.
//   --schools <file>  The Ministry of Education Schools Directory CSV
//                     (data.govt.nz, "Directory of educational institutions").
//                     Rows with Regional_Council "Canterbury Region" and
//                     Status "Open" are kept.
//   --out <file>      The migration to write.
//
// Licences: NZDep2023, University of Otago (cite Atkinson, Salmond, Crampton
// 2024); Schools Directory, Ministry of Education, CC BY 4.0.
//
// Usage:
//   node scripts/build-reference-lists.mjs --sa2 sa2.tsv --schools schooldirectory.csv \
//     --out supabase/migrations/<stamp>_reference_lists.sql

import { readFileSync, writeFileSync } from 'node:fs'

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith('--') ? [...acc, [a.slice(2), all[i + 1]]] : acc), []),
)
for (const k of ['sa2', 'schools', 'out']) {
  if (!args[k]) { console.error(`missing --${k}`); process.exit(1) }
}

const q = s => (s == null || s === '' ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`)

// ── Suburbs ──────────────────────────────────────────────────────────────────
const suburbs = readFileSync(args.sa2, 'utf8').trim().split('\n').map(line => {
  const [code, rawName, area, decile] = line.replace(/\r$/, '').split('\t')
  if (!/^\d{6}$/.test(code) || !/^([1-9]|10)$/.test(decile)) throw new Error(`bad SA2 line: ${line}`)
  // "Northlands (Christchurch City)": the district is shown beside the name.
  const name = rawName.replace(` (${area})`, '')
  return { code, name, area, decile: Number(decile) }
})

// ── Schools ──────────────────────────────────────────────────────────────────
/** A small CSV reader: quoted fields, doubled quotes, commas inside quotes. */
function parseCsv(text) {
  const rows = []
  let row = [], field = '', quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++ }
      else if (c === '"') quoted = false
      else field += c
    } else if (c === '"') quoted = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n') { row.push(field.replace(/\r$/, '')); rows.push(row); row = []; field = '' }
    else field += c
  }
  if (field || row.length) { row.push(field); rows.push(row) }
  return rows
}
const [head, ...body] = parseCsv(readFileSync(args.schools, 'utf8').replace(/^﻿/, ''))
const col = name => {
  const i = head.indexOf(name)
  if (i < 0) throw new Error(`schools CSV has no ${name} column`)
  return i
}
const [ID, NAME, SUBURB, CITY, KIND, REGION, STATUS] =
  ['School_Id', 'Org_Name', 'Add1_Suburb', 'Add1_City', 'Org_Type', 'Regional_Council', 'Status'].map(col)
const schools = body
  .filter(r => r[REGION] === 'Canterbury Region' && r[STATUS] === 'Open')
  .map(r => ({ id: Number(r[ID]), name: r[NAME].trim(), place: (r[SUBURB] || r[CITY]).trim(), kind: r[KIND] }))
  .sort((a, b) => a.id - b.id)
if (schools.some(s => !Number.isInteger(s.id))) throw new Error('a school has no number')

const sql = `-- ─── Suburb and school lists for "who plays" (multi-location PR 9) ──────────
-- GENERATED by scripts/build-reference-lists.mjs: do not hand-edit; re-run it.
-- Canterbury only (Tāne, 24 Nov 2026). Fills the lists 20261123230958 made.
--
--   nz_suburbs: ${suburbs.length} Canterbury statistical area 2 areas with their NZDep2023
--     decile (University of Otago; Atkinson, Salmond, Crampton 2024), plus the
--     "Somewhere else" row already there.
--   nz_schools: ${schools.length} open Canterbury schools from the Ministry of Education
--     Schools Directory (CC BY 4.0), downloaded 24 Nov 2026.
--
-- Safe to run again: existing rows are updated in place (a school renamed, a
-- decile revised); nothing is deleted, because profiles point at these rows.

INSERT INTO public.nz_suburbs (id, name, area, nzdep) VALUES
${suburbs.map(s => `  (${q(s.code)}, ${q(s.name)}, ${q(s.area)}, ${s.decile})`).join(',\n')}
ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, area = EXCLUDED.area, nzdep = EXCLUDED.nzdep;

INSERT INTO public.nz_schools (id, name, place, kind) VALUES
${schools.map(s => `  (${s.id}, ${q(s.name)}, ${q(s.place)}, ${q(s.kind)})`).join(',\n')}
ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, place = EXCLUDED.place, kind = EXCLUDED.kind;

DO $check$
BEGIN
  IF (SELECT count(*) FROM public.nz_suburbs WHERE nzdep IS NOT NULL) < ${suburbs.length}
     OR (SELECT count(*) FROM public.nz_schools) < ${schools.length} THEN
    RAISE EXCEPTION 'reference lists check: rows missing';
  END IF;
  RAISE NOTICE 'reference lists: ready';
END
$check$;
`
writeFileSync(args.out, sql)
console.log(`${suburbs.length} suburbs, ${schools.length} schools -> ${args.out}`)
